import { basename, isMarkdownFile } from "../config"

export type SidebarJsonItem =
  | string
  | ({ type: "doc" | "ref"; id: string; label?: string } & Record<
      string,
      unknown
    >)
  | ({
      type: "category"
      label: string
      items: SidebarJsonItem[]
      collapsed?: boolean
      collapsible?: boolean
      link?: unknown
    } & Record<string, unknown>)
  | ({ type: "link"; label: string; href: string } & Record<string, unknown>)
  | ({ type: "autogenerated"; dirName: string } & Record<string, unknown>)
  | ({ type: "html"; value: string } & Record<string, unknown>)

export type SidebarsJson = Record<string, SidebarJsonItem[]>

export type ItemPath = number[]

export function parseSidebars(text: string): SidebarsJson | null {
  try {
    const parsed = JSON.parse(text) as unknown
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed))
      return null
    for (const value of Object.values(parsed as Record<string, unknown>)) {
      if (!Array.isArray(value)) return null
    }
    return parsed as SidebarsJson
  } catch {
    return null
  }
}

export function serializeSidebars(sidebars: SidebarsJson): string {
  return `${JSON.stringify(sidebars, null, 2)}\n`
}

const NUMBER_PREFIX = /^\d+\s*[-_.]+\s*(.*)$/

function stripNumberPrefix(segment: string): string {
  const match = NUMBER_PREFIX.exec(segment)
  return match?.[1] ? match[1] : segment
}

export function docIdForFile(contentPath: string, file: string): string | null {
  const prefix = `${contentPath}/`
  if (!file.startsWith(prefix) || !isMarkdownFile(file)) return null
  const relative = file.slice(prefix.length).replace(/\.(md|mdx)$/i, "")
  return relative.split("/").map(stripNumberPrefix).join("/")
}

export function fileForDocId(
  contentPath: string,
  id: string,
  files: Iterable<string>,
  known?: Map<string, string>,
): string | null {
  const fromKnown = known?.get(id)
  if (fromKnown) return fromKnown
  for (const file of files) {
    if (docIdForFile(contentPath, file) === id) return file
  }
  return null
}

export function itemId(item: SidebarJsonItem): string | null {
  if (typeof item === "string") return item
  if (item.type === "doc" || item.type === "ref") return item.id
  return null
}

export function itemLabel(item: SidebarJsonItem): string | null {
  if (typeof item === "string") return null
  if ("label" in item && typeof item.label === "string") return item.label
  return null
}

export function referencedIds(items: SidebarJsonItem[]): Set<string> {
  const ids = new Set<string>()
  const walk = (list: SidebarJsonItem[]) => {
    for (const item of list) {
      const id = itemId(item)
      if (id) ids.add(id)
      if (typeof item !== "string" && item.type === "category") {
        walk(item.items)
        const link = item.link as { type?: string; id?: string } | undefined
        if (link?.type === "doc" && link.id) ids.add(link.id)
      }
    }
  }
  walk(items)
  return ids
}

function parentOf(
  items: SidebarJsonItem[],
  path: ItemPath,
): SidebarJsonItem[] | null {
  let list = items
  for (const index of path.slice(0, -1)) {
    const item = list[index]
    if (!item || typeof item === "string" || item.type !== "category")
      return null
    list = item.items
  }
  return list
}

export function getAt(
  items: SidebarJsonItem[],
  path: ItemPath,
): SidebarJsonItem | null {
  const parent = parentOf(items, path)
  return parent?.[path[path.length - 1]!] ?? null
}

function clone<T>(value: T): T {
  return JSON.parse(JSON.stringify(value)) as T
}

export function removeAt(
  items: SidebarJsonItem[],
  path: ItemPath,
): { items: SidebarJsonItem[]; removed: SidebarJsonItem | null } {
  const next = clone(items)
  const parent = parentOf(next, path)
  if (!parent) return { items: next, removed: null }
  const [removed] = parent.splice(path[path.length - 1]!, 1)
  return { items: next, removed: removed ?? null }
}

export function insertAt(
  items: SidebarJsonItem[],
  path: ItemPath,
  item: SidebarJsonItem,
): SidebarJsonItem[] {
  const next = clone(items)
  const parent = parentOf(next, path)
  if (!parent) return next
  const index = Math.max(0, Math.min(path[path.length - 1]!, parent.length))
  parent.splice(index, 0, clone(item))
  return next
}

function isAncestor(ancestor: ItemPath, path: ItemPath): boolean {
  if (ancestor.length >= path.length) return false
  return ancestor.every((index, position) => path[position] === index)
}

export function moveItem(
  items: SidebarJsonItem[],
  from: ItemPath,
  to: ItemPath,
): SidebarJsonItem[] {
  if (isAncestor(from, to)) return items
  const { items: without, removed } = removeAt(items, from)
  if (!removed) return items
  const target = [...to]
  const fromParent = from.slice(0, -1)
  const toParent = to.slice(0, -1)
  if (
    fromParent.length === toParent.length &&
    fromParent.every((index, position) => toParent[position] === index) &&
    from[from.length - 1]! < to[to.length - 1]!
  ) {
    target[target.length - 1] = to[to.length - 1]! - 1
  } else if (
    isAncestor(fromParent, toParent) &&
    toParent[fromParent.length]! > from[from.length - 1]!
  ) {
    target[fromParent.length] = toParent[fromParent.length]! - 1
  }
  return insertAt(without, target, removed)
}

export function updateAt(
  items: SidebarJsonItem[],
  path: ItemPath,
  update: (item: SidebarJsonItem) => SidebarJsonItem,
): SidebarJsonItem[] {
  const next = clone(items)
  const parent = parentOf(next, path)
  const index = path[path.length - 1]!
  if (!parent || parent[index] === undefined) return next
  parent[index] = update(parent[index]!)
  return next
}

export function newCategory(label: string): SidebarJsonItem {
  return { type: "category", label, items: [] }
}

export function displayLabel(
  item: SidebarJsonItem,
  titleForId: (id: string) => string | null,
): string {
  const label = itemLabel(item)
  if (label) return label
  const id = itemId(item)
  if (id) return titleForId(id) ?? basename(id)
  if (typeof item !== "string" && item.type === "autogenerated")
    return `Autogenerated from ${item.dirName}`
  if (typeof item !== "string" && item.type === "html") return "HTML block"
  return "Item"
}
