import fs from "node:fs"
import path from "node:path"

import type { LoadedContent } from "@docusaurus/plugin-content-docs"
import type { LoadContext, Plugin } from "@docusaurus/types"

import type {
  OutlineItem,
  OutlineVersion,
} from "../src/studio/core/model/outline"

interface RawSidebarItem {
  type: string
  id?: string
  label?: string
  href?: string
  items?: RawSidebarItem[]
  link?: { type: string; id?: string }
}

function hasAutogenerated(items: RawSidebarItem[]): boolean {
  return items.some(
    (item) =>
      item.type === "autogenerated" ||
      (item.type === "category" && hasAutogenerated(item.items ?? [])),
  )
}

function isManualSidebarFile(file: string | false | undefined): boolean {
  if (typeof file !== "string" || !file.endsWith(".json")) return false
  try {
    const raw = JSON.parse(fs.readFileSync(file, "utf8")) as Record<
      string,
      RawSidebarItem[]
    >
    return !Object.values(raw).some((items) =>
      hasAutogenerated(
        items.map((item) =>
          typeof item === "string" ? { type: "doc", id: item } : item,
        ),
      ),
    )
  } catch {
    return false
  }
}

function findCategoryFiles(dir: string): string[] {
  const found: string[] = []
  const walk = (current: string) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name)
      if (entry.isDirectory()) walk(full)
      else if (entry.name === "_category_.json") found.push(full)
    }
  }
  if (fs.existsSync(dir)) walk(dir)
  return found
}

/**
 * Exposes the sidebars Docusaurus computed for every docs instance and version
 * as global data, so the docs studio can show the same structure without
 * fetching a single page. Also warns about docs that no sidebar references.
 */
export default function studioSidebarPlugin(context: LoadContext): Plugin {
  const toFile = (source: string) =>
    source.startsWith("@site/")
      ? source.slice("@site/".length)
      : path.relative(context.siteDir, source)

  return {
    name: "studio-sidebar",
    async allContentLoaded({ allContent, actions }) {
      const instances = (allContent["docusaurus-plugin-content-docs"] ??
        {}) as Record<string, LoadedContent>
      const versions: OutlineVersion[] = []
      for (const [pluginId, content] of Object.entries(instances)) {
        for (const version of content.loadedVersions) {
          const docsById = new Map(version.docs.map((doc) => [doc.id, doc]))
          const convert = (items: RawSidebarItem[]): OutlineItem[] => {
            const result: OutlineItem[] = []
            for (const item of items) {
              if ((item.type === "doc" || item.type === "ref") && item.id) {
                const doc = docsById.get(item.id)
                if (doc) {
                  result.push({
                    type: "doc",
                    id: doc.id,
                    file: toFile(doc.source),
                    label: item.label ?? doc.title,
                  })
                }
              } else if (item.type === "category") {
                const linked =
                  item.link?.type === "doc" && item.link.id
                    ? docsById.get(item.link.id)
                    : null
                result.push({
                  type: "category",
                  label: item.label ?? "",
                  file: linked ? toFile(linked.source) : null,
                  items: convert(item.items ?? []),
                })
              } else if (item.type === "link" && item.href) {
                result.push({
                  type: "link",
                  label: item.label ?? item.href,
                  href: item.href,
                })
              }
            }
            return result
          }
          const manual = isManualSidebarFile(version.sidebarFilePath)
          if (manual) {
            const stale = findCategoryFiles(version.contentPath)
            if (stale.length > 0) {
              console.warn(
                `[studio-sidebar] ${pluginId}/${version.versionName} uses an explicit sidebar, these _category_.json files have no effect: ${stale
                  .map((file) => path.relative(context.siteDir, file))
                  .join(", ")}`,
              )
            }
          }
          const orphans = version.docs.filter(
            (doc) => !doc.sidebar && !doc.unlisted,
          )
          if (orphans.length > 0) {
            console.warn(
              `[studio-sidebar] ${orphans.length} doc(s) in ${pluginId}/${version.versionName} are not in any sidebar: ${orphans
                .map((doc) => toFile(doc.source))
                .join(", ")}`,
            )
          }
          versions.push({
            pluginId,
            version: version.versionName,
            label: version.label,
            title:
              pluginId === "default"
                ? content.loadedVersions.length > 1
                  ? `Docs ${version.label}`
                  : "Docs"
                : pluginId.charAt(0).toUpperCase() + pluginId.slice(1),
            contentPath: path.relative(context.siteDir, version.contentPath),
            sidebarFile:
              typeof version.sidebarFilePath === "string"
                ? path.relative(context.siteDir, version.sidebarFilePath)
                : null,
            manual,
            className: version.className,
            isLast: version.isLast,
            sidebars: Object.fromEntries(
              Object.entries(version.sidebars).map(([id, items]) => [
                id,
                convert(items as RawSidebarItem[]),
              ]),
            ),
            docs: version.docs.map((doc) => ({
              id: doc.id,
              file: toFile(doc.source),
              editFile:
                typeof doc.frontMatter.studio_source === "string"
                  ? doc.frontMatter.studio_source
                  : null,
              title: doc.title,
              sidebar: doc.sidebar ?? null,
              unlisted: doc.unlisted,
            })),
          })
        }
      }
      actions.setGlobalData({ versions })
    },
  }
}
