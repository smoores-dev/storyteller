    static func linearSrgbToOklab(r: Float, g: Float, b: Float) -> OkmainOklab {
        let l = (0.5363325363 * g).addingProduct(0.4122214708, r).addingProduct(0.0514459929, b)
        let m = (0.6806995451 * g).addingProduct(0.2119034982, r).addingProduct(0.1073969566, b)
        let s = (0.2817188376 * g).addingProduct(0.0883024619, r).addingProduct(0.6299787005, b)
        let lc = cbrt(l)
        let mc = cbrt(m)
        let sc = cbrt(s)
        return OkmainOklab(
            l: (0.7936177850 * mc).addingProduct(0.2104542553, lc).addingProduct(-0.0040720468, sc),
            a: (-2.4285922050 * mc).addingProduct(1.9779984951, lc).addingProduct(0.4505937099, sc),
            b: (0.7827717662 * mc).addingProduct(0.0259040371, lc).addingProduct(-0.8086757660, sc),
        )
    }

    static func oklabToSrgb(_ c: OkmainOklab) -> (r: UInt8, g: UInt8, b: UInt8) {
        let lc = c.l.addingProduct(0.3963377774, c.a).addingProduct(0.2158037573, c.b)
        let mc = c.l.addingProduct(-0.1055613458, c.a).addingProduct(-0.0638541728, c.b)
        let sc = c.l.addingProduct(-0.0894841775, c.a).addingProduct(-1.2914855480, c.b)
        let l = lc * lc * lc
        let m = mc * mc * mc
        let s = sc * sc * sc
        let r = (-3.3077115913 * m).addingProduct(4.0767416621, l).addingProduct(0.2309699292, s)
        let g = (2.6097574011 * m).addingProduct(-1.2684380046, l).addingProduct(-0.3413193965, s)
        let b = (-0.7034186147 * m).addingProduct(-0.0041960863, l).addingProduct(1.7076147010, s)
        return (floatToSrgb8(r), floatToSrgb8(g), floatToSrgb8(b))
    }

    /// oklab crate's branch-free cube root approximation (its non-std default).
    static func cbrt(_ x: Float) -> Float {
        let bMagic: UInt32 = 709_957_561
        let c: Float = 5.4285717010e-1
        let d: Float = -7.0530611277e-1
        let e: Float = 1.4142856598e+0
        let f: Float = 1.6071428061e+0
        let g: Float = 3.5714286566e-1

        var t = Float(bitPattern: (x.bitPattern / 3) &+ bMagic)
        let s = c + (t * t) * (t / x)
        t *= g + f / (s + e + d / s)
        return t
    }

    static func srgb8ToFloat(_ c: UInt8) -> Float {
        fromSrgb8Table[Int(c)]
    }

    static func floatToSrgb8(_ value: Float) -> UInt8 {
        let minvBits: UInt32 = 0x3900_0000
        let maxvBits: UInt32 = 0x3F7F_FFFF
        let minv = Float(bitPattern: minvBits)
        let maxv = Float(bitPattern: maxvBits)

        var input = value
        if !(input > minv) { input = minv }
        if input > maxv { input = maxv }

        let fu = input.bitPattern
        let entry = toSrgb8Table[Int((fu - minvBits) >> 20)]
        let bias = (entry >> 16) << 9
        let scale = entry & 0xFFFF
        let t = (fu >> 12) & 0xFF
        return UInt8(truncatingIfNeeded: (bias &+ scale &* t) >> 16)
    }

